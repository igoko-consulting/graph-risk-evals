import duckdb

from loaders import get_dataset, validate
from paths import COLUMNAR_STORE, DATA_NOTES, DATASET, RAW
from protocol import PERIODS, require_k_first
from results_io import read_result, write_result

START = "<!-- generated by 00-build/day_one_checks.py from results/; do not edit by hand -->"
END = "<!-- end generated -->"


def edge_checks(con) -> dict:
    q = lambda sql: con.execute(sql).fetchone()[0]
    cross = q(
        "SELECT count(*) FROM edges e JOIN nodes a ON a.node_id = e.src JOIN nodes b ON b.node_id = e.dst "
        "WHERE a.time_step <> b.time_step"
    )
    backward = q(
        "SELECT count(*) FROM edges e JOIN nodes a ON a.node_id = e.src JOIN nodes b ON b.node_id = e.dst "
        "WHERE b.time_step < a.time_step"
    )
    return {
        "edges_crossing_time_steps": cross,
        "edges_pointing_to_an_earlier_step": backward,
        "time_steps_are_disjoint": cross == 0,
        "self_loops": q("SELECT count(*) FROM edges WHERE src = dst"),
        "duplicate_edges": q("SELECT count(*) - (SELECT count(*) FROM (SELECT DISTINCT src, dst FROM edges)) FROM edges"),
        "isolated_nodes": q(
            "SELECT count(*) FROM nodes n WHERE n.node_id NOT IN (SELECT src FROM edges) AND n.node_id NOT IN (SELECT dst FROM edges)"
        ),
    }


def render_notes(checks: dict, k: dict, balance: dict) -> str:
    d = checks["data"]
    c, s, raw, e = d["counts_against_prd"], d["label_shares_against_prd"], d["raw_file_shape"], d["edges"]
    prov = checks["provenance"]["dataset"]
    lines = [START, "", "## Day-one checks", ""]
    lines += [f"Source: `{prov['source']}`. Files verified against pinned SHA-256 checksums.", ""]
    lines += ["| Check | PRD | Observed | Within tolerance |", "|---|---|---|---|"]
    for key, v in c.items():
        lines.append(f"| {key.replace('_', ' ')} | {v['prd']:,} | {v['observed']:,} | {'yes' if v['within_tolerance'] else 'NO'} |")
    for key, v in s.items():
        lines.append(f"| {key} share | {v['prd']:.0%} | {v['observed']:.2%} | {'yes' if v['within_tolerance'] else 'NO'} |")
    ts = raw["time_step_column"]
    lines += [
        "",
        "### Feature split",
        "",
        f"- Raw feature file: {raw['raw_columns']} columns, transaction id plus {raw['raw_feature_columns']} features.",
        f"- Time step: raw column {ts['index']}, integer valued, {ts['min']} to {ts['max']}, {ts['distinct']} distinct values. "
        "Held in `nodes.time_step`, never in the `features` table.",
        f"- Local: raw columns {raw['local_columns']['indices'][0]} to {raw['local_columns']['indices'][1]}, "
        f"{raw['local_columns']['count']} features (`{raw['local_columns']['names'][0]}` to `{raw['local_columns']['names'][1]}`). "
        f"With the time step these are the {raw['local_columns']['count'] + 1} local features the paper describes.",
        f"- Aggregate: raw columns {raw['aggregate_columns']['indices'][0]} to {raw['aggregate_columns']['indices'][1]}, "
        f"{raw['aggregate_columns']['count']} features (`{raw['aggregate_columns']['names'][0]}` to `{raw['aggregate_columns']['names'][1]}`).",
        "- The split follows the dataset paper. The values are anonymised, so the data confirms the counts and the "
        "time-step column, not which columns are semantically local.",
        "",
        "### Edges",
        "",
        f"- Edges crossing time steps: **{e['edges_crossing_time_steps']:,}**. "
        + ("Time steps are disjoint graphs." if e["time_steps_are_disjoint"] else "Time steps are NOT disjoint. Leakage design must be revisited."),
        f"- Edges pointing to an earlier step: {e['edges_pointing_to_an_earlier_step']:,}.",
        f"- Self-loops: {e['self_loops']:,}. Duplicate edges: {e['duplicate_edges']:,}. Nodes with no edges: {e['isolated_nodes']:,}.",
        "",
        "### Operating point",
        "",
        f"- Mean illicit labels per step over steps {k['data']['steps'][0]} to {k['data']['steps'][1]}: "
        f"{k['data']['k_mean']:.4f} ({k['data']['illicit_labels_total']:,} labels over "
        f"{len(k['data']['illicit_labels_per_step'])} steps). Computed before any test step is read.",
        f"- k used for precision at k: **{k['data']['k']}**. Rule: {k['data']['integer_rule']}.",
        "",
        "### Labels by time step",
        "",
        "Illicit share is over labelled nodes only. Unlabelled is not licit.",
        "",
        "| Step | Period | Illicit | Licit | Unknown | Illicit share of labelled |",
        "|---|---|---|---|---|---|",
    ]
    for row in balance["data"]["by_time_step"]:
        share = row["illicit_share_of_labelled"]
        lines.append(
            f"| {row['time_step']} | {row['period'].replace('_', ' ')} | {row['illicit']:,} | {row['licit']:,} | "
            f"{row['unknown']:,} | {'n/a' if share is None else f'{share:.1%}'} |"
        )
    lines += ["", END]
    return "\n".join(lines)


def write_notes(block: str) -> None:
    text = DATA_NOTES.read_text()
    if START in text and END in text:
        head, rest = text.split(START, 1)
        tail = rest.split(END, 1)[1]
        text = head + block + tail
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    DATA_NOTES.write_text(text)


def main() -> None:
    k = require_k_first()
    dataset = get_dataset(DATASET)
    with duckdb.connect(str(COLUMNAR_STORE), read_only=True) as con:
        contract = validate(con, dataset)
        edges = edge_checks(con)
        with duckdb.connect() as scratch:
            raw = dataset.raw_shape(RAW, scratch)
    if raw["raw_feature_columns"] != dataset.expected.raw_feature_columns:
        raise SystemExit(f"STOP: {raw['raw_feature_columns']} raw features, PRD states {dataset.expected.raw_feature_columns}")
    if raw["local_columns"]["count"] + 1 != dataset.expected.feature_groups["local_including_time_step"]:
        raise SystemExit("STOP: local feature count does not match the PRD")
    write_result("day-one-checks", {
        **contract,
        "raw_file_shape": raw,
        "feature_groups_used": {name: len(cols) for name, cols in dataset.feature_groups.items()},
        "edges": edges,
        "periods": PERIODS,
    })
    checks = read_result("day-one-checks")
    write_notes(render_notes(checks, k, read_result("class-balance-by-time-step")))
    print(f"edges crossing time steps: {edges['edges_crossing_time_steps']}")
    if not edges["time_steps_are_disjoint"]:
        print("STOP: edges cross time steps. Leakage-dependent work is paused until this is decided.")
    print(f"day-one checks written to results/ and {DATA_NOTES.parent.name}/{DATA_NOTES.name}")


if __name__ == "__main__":
    main()
